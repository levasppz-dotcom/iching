// 3. АУТЕНТИЧНЫЙ АЛГОРИТМ ГАДАНИЯ НА СТЕБЛЯХ ТЫСЯЧЕЛИСТНИКА (ШИ ЦАО / 蓍草)
// Вероятности строго канонические:
//   6 (Старая Инь — ⚋× меняющаяся в Ян) : 1/16
//   7 (Молодой Ян — ⚊ неизменная)       : 5/16
//   8 (Молодая Инь — ⚋ неизменная)      : 7/16
//   9 (Старый Ян  — ⚊○ меняющаяся в Инь): 3/16
// ============================================================================
function performSingleYarrowChange(currentStalks, splitRatio = null) {
  let left;
  if (splitRatio !== null && splitRatio > 0.15 && splitRatio < 0.85) {
    left = Math.max(4, Math.min(currentStalks - 4, Math.round(currentStalks * splitRatio)));
  } else {
    // Естественное распределение вокруг середины пучка
    const mid = Math.floor(currentStalks / 2);
    const offset = Math.floor((Math.random() - 0.5) * 14);
    left = Math.max(4, Math.min(currentStalks - 4, mid + offset));
  }
  const right = currentStalks - left;

  // 1 стебель из правой кучки зажимается между мизинцем и безымянным пальцем (Человек / Жэнь)
  const human = 1;
  const rightAfterHuman = right - 1;

  // Отсчёт по 4 стебля (Четыре времени года) из левой кучки
  let remLeft = left % 4;
  if (remLeft === 0) remLeft = 4;

  // Отсчёт по 4 стебля из правой кучки
  let remRight = rightAfterHuman % 4;
  if (remRight === 0) remRight = 4;

  // Отложенные стебли (1 + remLeft + remRight).
  // На 1-м изменении это всегда 5 или 9; на 2-м и 3-м — всегда 4 или 8.
  const removed = human + remLeft + remRight;
  const remaining = currentStalks - removed;

  return {
    before: currentStalks,
    left,
    right,
    human,
    remLeft,
    remRight,
    removed,
    remaining
  };
}

// Полный расчёт одной черты через Три Изменения (Сань бянь)
function computeCompleteLineFromYarrow(firstSplitRatio = null) {
  const c1 = performSingleYarrowChange(49, firstSplitRatio);
  const c2 = performSingleYarrowChange(c1.remaining);
  const c3 = performSingleYarrowChange(c2.remaining);

  // Остаток после 3-го изменения (24, 28, 32 или 36) делится на 4 -> получаем 6, 7, 8 или 9
  const lineValue = c3.remaining / 4;

  return {
    value: lineValue, // 6, 7, 8, 9
    changes: [c1, c2, c3],
    isYang: lineValue === 7 || lineValue === 9,
    isChanging: lineValue === 6 || lineValue === 9,
    transformedIsYang: lineValue === 7 || lineValue === 6 // 9->Инь(0), 6->Ян(1)
  };
}

