// 1) Если приложение развёрнуто на Vercel с файлом /api/oracle.js — идёт через защищённый серверный прокси (ключ спрятан на сервере, работает без VPN).
// 2) Если задан пользовательский ключ (или внутри среды Canvas) — вызывает Gemini API напрямую.
async function callGeminiOracle(payload, userApiKey = '') {
  const envKey =
    (typeof window !== 'undefined' && window.__GEMINI_API_KEY__) || '';
  const effectiveKey = (userApiKey || envKey || '').trim();

  const isExternalHost =
    typeof window !== 'undefined' &&
    (window.location.hostname.endsWith('.vercel.app') ||
      window.location.hostname.endsWith('.netlify.app') ||
      window.location.hostname.endsWith('.pages.dev'));

  if (isExternalHost && !effectiveKey) {
    try {
      const proxyRes = await fetch('/api/oracle', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({ payload })
      });
      if (proxyRes.ok) {
        return await proxyRes.json();
      }
    } catch {
      // Переходим к прямому вызову, если прокси недоступен
    }
  }

  const directUrl = `https://generativelanguage.googleapis.com/v1beta/models/gemini-2.5-flash-preview-09-2025:generateContent?key=${effectiveKey}`;
  try {
    return await fetchWithBackoff(directUrl, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify(payload)
    });
  } catch (directErr) {
    const proxyRes = await fetch('/api/oracle', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ payload })
    });
    if (proxyRes.ok) {
      return await proxyRes.json();
    }
    throw directErr;
  }
}

