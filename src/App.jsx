// Получение данных гексаграммы по массиву из 6 чисел (6, 7, 8, 9) снизу вверх
function resolveHexagramsFromLines(lines) {
  if (!lines || lines.length < 6) return null;

  const primaryBits = lines.map((l) => (l.value === 7 || l.value === 9 ? '1' : '0'));
  const transformedBits = lines.map((l) => {
    if (l.value === 9) return '0'; // Старый Ян -> Инь
    if (l.value === 6) return '1'; // Старая Инь -> Ян
    return l.value === 7 ? '1' : '0';
  });

  const lowerPrimaryBin = primaryBits.slice(0, 3).join('');
  const upperPrimaryBin = primaryBits.slice(3, 6).join('');
  const primaryNum = KING_WEN_MATRIX[`${lowerPrimaryBin}_${upperPrimaryBin}`] || 1;

  const lowerTransBin = transformedBits.slice(0, 3).join('');
  const upperTransBin = transformedBits.slice(3, 6).join('');
  const transformedNum = KING_WEN_MATRIX[`${lowerTransBin}_${upperTransBin}`] || 1;

  const changingIndices = lines
    .map((l, idx) => (l.value === 6 || l.value === 9 ? idx + 1 : null))
    .filter(Boolean);

  return {
    primaryHex: HEXAGRAMS[primaryNum],
    transformedHex: changingIndices.length > 0 ? HEXAGRAMS[transformedNum] : null,
    lowerTrigram: TRIGRAMS[lowerPrimaryBin],
    upperTrigram: TRIGRAMS[upperPrimaryBin],
    transLowerTrigram: TRIGRAMS[lowerTransBin],
    transUpperTrigram: TRIGRAMS[upperTransBin],
    changingIndices,
    hasChanges: changingIndices.length > 0
  };
}

