// Каллиграфическое начертание одной черты гексаграммы кистью (Суми-э SVG)
function BrushHexLine({
  value = 7, // 6, 7, 8, 9 или булево для мини-превью
  index = 0, // 0..5 снизу вверх
  showLabels = true,
  compact = false,
  highlightChanging = true,
  animateIn = false
}) {
  const isYang = value === 7 || value === 9 || value === 1;
  const isChanging = (value === 6 || value === 9) && highlightChanging;

  const heightClass = compact ? 'h-4' : 'h-8 sm:h-9';

  return (
    <div
      className={`group relative flex items-center gap-2 sm:gap-3 w-full ${heightClass} transition-all duration-500 ${
        animateIn ? 'animate-pulse' : ''
      }`}
    >
      {showLabels && (
        <div className="w-7 sm:w-8 text-right font-mono text-[11px] sm:text-xs text-[#9b8e78] select-none">
          {index + 1}-я
        </div>
      )}

      {/* Полотно мазка тушью */}
      <div className="relative flex-1 flex items-center justify-center h-full">
        <svg
          viewBox="0 0 320 34"
          className="w-full h-full overflow-visible drop-shadow-[0_2px_4px_rgba(0,0,0,0.45)]"
        >
          <defs>
            <linearGradient id={`inkGrad_${index}_${value}`} x1="0%" y1="0%" x2="100%" y2="0%">
              <stop offset="0%" stopColor={isChanging ? '#d9534f' : '#e2d5be'} stopOpacity="0.92" />
              <stop offset="50%" stopColor={isChanging ? '#e8b960' : '#f4efe6'} stopOpacity="1" />
              <stop offset="96%" stopColor={isChanging ? '#d9534f' : '#cbb999'} stopOpacity="0.9" />
              <stop offset="100%" stopColor={isChanging ? '#b3392b' : '#9c8b70'} stopOpacity="0.55" />
            </linearGradient>
          </defs>

          {isYang ? (
            // Сплошная черта Ян (с органичным каллиграфическим нажимом кисти)
            <g>
              <path
                d="M 8,18 C 22,10 68,11 160,12 C 235,12 288,10 312,16 C 316,18 313,24 298,25 C 230,24 95,25 18,24 C 7,24 4,21 8,18 Z"
                fill={`url(#inkGrad_${index}_${value})`}
              />
              {/* Тонкие штрихи сухой кисти (Фэйбай) */}
              <path
                d="M 285,15 L 310,17 M 275,21 L 306,21"
                stroke="#181614"
                strokeWidth="1.1"
                strokeOpacity="0.45"
                strokeLinecap="round"
              />
            </g>
          ) : (
            // Прерывистая черта Инь (два каллиграфических сегмента с разрывом в центре)
            <g>
              <path
                d="M 8,18 C 18,11 55,11 124,13 C 132,14 134,22 122,24 C 75,24 26,24 14,24 C 7,23 5,20 8,18 Z"
                fill={`url(#inkGrad_${index}_${value})`}
              />
              <path
                d="M 192,16 C 204,11 258,11 310,16 C 315,18 312,24 299,24 C 255,24 212,24 196,23 C 188,22 187,18 192,16 Z"
                fill={`url(#inkGrad_${index}_${value})`}
              />
            </g>
          )}

          {/* Знак меняющейся (старой) черты: ○ для Старого Ян (9), × для Старой Инь (6) */}
          {isChanging && value === 9 && (
            <circle
              cx="160"
              cy="18"
              r="9.5"
              fill="#181614"
              stroke="#e55a47"
              strokeWidth="2.5"
            />
          )}
          {isChanging && value === 6 && (
            <g stroke="#e55a47" strokeWidth="2.6" strokeLinecap="round">
              <line x1="152" y1="10" x2="168" y2="26" />
              <line x1="168" y1="10" x2="152" y2="26" />
            </g>
          )}
        </svg>
      </div>

      {showLabels && (
        <div className="w-16 sm:w-20 flex items-center justify-end gap-1.5 select-none">
          <span
            className={`px-1.5 py-0.5 rounded text-[11px] font-mono ${
              isChanging
                ? 'bg-[#b3392b]/25 text-[#f29b8f] border border-[#b3392b]/50 font-semibold'
                : 'bg-[#2a2622] text-[#b5a892]'
            }`}
          >
            {value === 9 ? '9 ○' : value === 6 ? '6 ×' : value === 7 ? '7 —' : '8 - -'}
          </span>
        </div>
      )}
    </div>
  );
}

// Интерактивная визуализация пучка стеблей тысячелистника на циновке
function YarrowStalksCanvas({
  lines,
  activeSubStep, // null или { lineIdx, changeIdx, data }
  splitHoverRatio,
  setSplitHoverRatio,
  onManualSplit,
  isAutoCasting
}) {
  // Генерируем стабильные углы наклона для 50 стеблей, чтобы они выглядели как настоящие сухие стебли
  const stalkSeeds = useMemo(() => {
    return Array.from({ length: 50 }, (_, idx) => ({
      id: idx,
      angle: ((idx * 37) % 11) - 5,
      yOffset: ((idx * 19) % 9) - 4,
      thickness: 2 + (idx % 2) * 0.6
    }));
  }, []);

  const currentLineNumber = lines.length + 1;
  const isComplete = lines.length >= 6;

  // Обработка движения мыши/пальца по пучку для выбора точки разделения (Фэнь эр)
  const handlePointerMove = (e) => {
    if (isComplete || isAutoCasting) return;
    const rect = e.currentTarget.getBoundingClientRect();
    const clientX = e.touches ? e.touches[0].clientX : e.clientX;
    const rawRatio = (clientX - rect.left) / rect.width;
    const clamped = Math.max(0.22, Math.min(0.78, rawRatio));
    setSplitHoverRatio(clamped);
  };

  const handleBundleClick = () => {
    if (isComplete || isAutoCasting) return;
    onManualSplit(splitHoverRatio);
  };

  // Определяем, сколько стеблей в левой (Небо) и правой (Земля) руке в текущий момент
  const latestChange = activeSubStep?.data;
  const leftCount = latestChange ? latestChange.left : Math.round(49 * splitHoverRatio);
  const rightCount = latestChange ? latestChange.right : 49 - leftCount;

  return (
    <div className="relative rounded-xl border border-[#c5a059]/30 bg-gradient-to-b from-[#1c1916] via-[#151310] to-[#1a1714] p-4 sm:p-6 shadow-2xl overflow-hidden">
      {/* Фоновый водяной знак Тайцзи и Багуа */}
      <div className="pointer-events-none absolute inset-0 flex items-center justify-center opacity-[0.04] select-none">
        <span className="text-[190px] sm:text-[240px] font-serif text-[#e5c478]">☯</span>
      </div>

      {/* Верхняя планка: 50-й стебель Великого Предела (Тайцзи) */}
      <div className="relative z-10 flex flex-col sm:flex-row sm:items-center justify-between gap-2 pb-3 mb-4 border-b border-[#c5a059]/20">
        <div className="flex items-center gap-2.5">
          <span className="inline-block w-2.5 h-2.5 rounded-full bg-[#c5a059] shadow-[0_0_8px_#c5a059]" />
          <span className="text-xs sm:text-sm font-serif text-[#d8cbb5]">
            <strong>Великий Предел (Тайцзи):</strong> 1 стебель из 50 отложен и не трогается — свидетель Единства
          </span>
        </div>
        <div className="text-xs font-mono text-[#c5a059] bg-[#26221d] px-2.5 py-1 rounded border border-[#c5a059]/30">
          В работе: 49 стеблей
        </div>
      </div>

      {/* Визуализация отложенного 50-го стебля */}
      <div className="relative z-10 flex justify-center mb-4">
        <div className="w-56 sm:w-72 h-2 rounded-full bg-gradient-to-r from-[#8b6b35] via-[#e5c478] to-[#8b6b35] shadow-[0_0_12px_rgba(229,196,120,0.35)]" />
      </div>

      {/* Основная сцена со стеблями */}
      <div
        onMouseMove={handlePointerMove}
        onTouchMove={handlePointerMove}
        onClick={handleBundleClick}
        className={`relative z-10 h-48 sm:h-56 rounded-lg border border-[#c5a059]/20 bg-[#110f0d]/80 flex flex-col justify-between p-3 sm:p-4 select-none transition ${
          !isComplete && !isAutoCasting
            ? 'cursor-pointer hover:border-[#c5a059]/60'
            : 'cursor-default'
        }`}
      >
        {/* Подсказка над стеблями */}
        <div className="flex items-center justify-between text-xs text-[#a89b84]">
          <span>
            Небо (Левая доля / Тянь): <strong className="text-[#e5c478]">{leftCount}</strong> стеблей
          </span>
          {!isComplete && (
            <span className="text-[11px] text-[#c5a059] animate-pulse hidden sm:inline">
              Нажмите на пучок, чтобы разделить 49 стеблей ({currentLineNumber}-я черта)
            </span>
          )}
          <span>
            Земля (Правая доля / Ди): <strong className="text-[#e5c478]">{rightCount}</strong> стеблей
          </span>
        </div>

        {/* SVG-отрисовка 49 рабочих стеблей тысячелистника */}
        <div className="relative flex-1 flex items-center justify-center my-1">
          <svg viewBox="0 0 600 130" className="w-full h-full overflow-visible">
            <defs>
              <linearGradient id="yarrowStalkGrad" x1="0%" y1="0%" x2="0%" y2="100%">
                <stop offset="0%" stopColor="#f0d799" />
                <stop offset="45%" stopColor="#c5a059" />
                <stop offset="85%" stopColor="#856834" />
                <stop offset="100%" stopColor="#5c4620" />
              </linearGradient>
              <linearGradient id="yarrowHighlightGrad" x1="0%" y1="0%" x2="0%" y2="100%">
                <stop offset="0%" stopColor="#ffdf9e" />
                <stop offset="50%" stopColor="#e06d53" />
                <stop offset="100%" stopColor="#9e2a1f" />
              </linearGradient>
            </defs>

            {stalkSeeds.slice(0, 49).map((stalk, idx) => {
              const isLeftGroup = idx < leftCount;
              const isHumanStalk = latestChange && idx === leftCount;
              const isRemainderStalk =
                latestChange &&
                ((idx >= leftCount - latestChange.remLeft && idx < leftCount) ||
                  idx > 49 - latestChange.remRight);

              // Раздвигаем левую и правую кучки вокруг точки разлома
              const baseSpread = 470;
              const rawX = 65 + (idx / 48) * baseSpread;
              const groupShift = latestChange
                ? isLeftGroup
                  ? -22
                  : isHumanStalk
                  ? 0
                  : 22
                : idx < Math.round(49 * splitHoverRatio)
                ? -10
                : 10;

              const xPos = rawX + groupShift;
              const yTop = 14 + stalk.yOffset + (isHumanStalk || isRemainderStalk ? -10 : 0);
              const yBottom = 116 + stalk.yOffset + (isHumanStalk || isRemainderStalk ? -10 : 0);

              return (
                <g key={stalk.id} className="transition-all duration-300">
                  <line
                    x1={xPos - stalk.angle * 0.8}
                    y1={yTop}
                    x2={xPos + stalk.angle * 0.8}
                    y2={yBottom}
                    stroke={
                      isHumanStalk || isRemainderStalk
                        ? 'url(#yarrowHighlightGrad)'
                        : 'url(#yarrowStalkGrad)'
                    }
                    strokeWidth={isHumanStalk ? 3.2 : stalk.thickness}
                    strokeLinecap="round"
                    opacity={isHumanStalk || isRemainderStalk ? 1 : 0.88}
                  />
                  {/* Узелок на стебле тысячелистника */}
                  <circle
                    cx={xPos}
                    cy={(yTop + yBottom) / 2 + (idx % 3) * 6 - 6}
                    r={1.3}
                    fill="#3d2e14"
                  />
                </g>
              );
            })}

            {/* Вертикальный золотой маркер разделения Неба и Земли */}
            {!isComplete && (
              <g>
                <line
                  x1={65 + splitHoverRatio * 470}
                  y1={4}
                  x2={65 + splitHoverRatio * 470}
                  y2={126}
                  stroke="#e06d53"
                  strokeWidth="1.5"
                  strokeDasharray="4 4"
                />
                <circle cx={65 + splitHoverRatio * 470} cy={65} r={5} fill="#e06d53" />
              </g>
            )}
          </svg>
        </div>

        {/* Нижняя строка: формула текущего изменения (Сань бянь) */}
        <div className="flex flex-wrap items-center justify-between gap-2 text-[11px] sm:text-xs text-[#b5a892] border-t border-[#c5a059]/15 pt-2">
          {latestChange ? (
            <>
              <div>
                Изменение {activeSubStep.changeIdx}/3: левая{' '}
                <strong className="text-[#f4efe6]">{latestChange.left}</strong> (остаток по 4:{' '}
                <strong className="text-[#e06d53]">{latestChange.remLeft}</strong>) + 1 (Человек) + правая{' '}
                <strong className="text-[#f4efe6]">{latestChange.right - 1}</strong> (остаток:{' '}
                <strong className="text-[#e06d53]">{latestChange.remRight}</strong>)
              </div>
              <div className="font-mono text-[#e5c478]">
                Отложено: {latestChange.removed} → Осталось: {latestChange.remaining}
              </div>
            </>
          ) : isComplete ? (
            <div className="text-[#7ab893] font-medium">
              Все 6 черт начертаны снизу вверх (18 изменений завершены). Гексаграмма обрела форму.
            </div>
          ) : (
            <div>
              Разделите пучок кликом в любом месте или нажмите кнопку{' '}
              <span className="text-[#e5c478]">«Разделить стебли»</span> ниже
            </div>
          )}
        </div>
      </div>
    </div>
  );
}

